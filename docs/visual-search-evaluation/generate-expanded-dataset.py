def q(id, query, vision, gt, expected, notes):
    return {
        "id": id,
        "query": query,
        "vision_output": vision,
        "ground_truth": gt,
        "expected_top3": expected,
        "notes": notes,
    }

def make_gt(relevant_ids, partial_ids=None, marginal_ids=None):
    """Create ground truth dict. relevant=3, partial=2, marginal=1, rest=0."""
    gt = {pid: 0 for pid in PRODUCTS}
    for pid in (relevant_ids or []):
        if pid in gt: gt[pid] = 3
    for pid in (partial_ids or []):
        if pid in gt and gt[pid] == 0: gt[pid] = 2
    for pid in (marginal_ids or []):
        if pid in gt and gt[pid] == 0: gt[pid] = 1
    return gt

